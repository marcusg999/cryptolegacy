/**
 * The two operations everything else is built on: create a vault, unlock a vault.
 *
 * Both run entirely in the browser. `createVault` returns records to persist and a
 * live VMK; `unlockVault` takes records from the server and returns a live VMK.
 * Neither sends anything anywhere — the caller does the I/O, with the records,
 * which contain no secret.
 */

import { AeadError } from './aead';
import {
  CURRENT_KDF_PROFILE,
  assertProductionProfile,
  type KdfProfile,
} from './constants';
import { createVaultMasterKey, unwrapVaultMasterKey, verifySentinel, wrapVaultMasterKeyBytes } from './envelope';
import { deriveKeyEncryptionKey, newKdfSalt, resolveKdfProfile } from './kdf';
import { base64ToBytes, bytesToBase64 } from './encoding';
import {
  blobToRecord,
  recordToBlob,
  recordToWrappedKey,
  wrappedKeyToRecord,
  type VaultKeyKind,
  type VaultKeyRecord,
} from './records';

export class WrongPassphraseError extends Error {
  constructor() {
    super('That passphrase does not open this vault.');
    this.name = 'WrongPassphraseError';
  }
}

export interface CreateVaultInput {
  /** Generated by `generatePassphrase`. Never a user-authored string. */
  readonly passphrase: string;
  readonly vaultId: string;
  readonly keyRecordId: string;
  readonly profile?: KdfProfile;
  readonly onProgress?: (fraction: number) => void;
  /**
   * Opt in to the deliberately cheap test cost profile. Tests of the vault
   * lifecycle need it, because running Argon2id at production cost dozens of times
   * turns a 1-second suite into a 1-minute one.
   *
   * It is a named, explicit flag rather than an environment check so that it is
   * greppable: `scripts/check-crypto-leaks.mjs` fails the build if this flag
   * appears anywhere outside `tests/`.
   */
  readonly allowTestProfile?: boolean;
}

export interface CreateVaultResult {
  readonly keyRecord: VaultKeyRecord;
  readonly vaultMasterKey: CryptoKey;
}

export async function createVault(input: CreateVaultInput): Promise<CreateVaultResult> {
  const profile = input.profile ?? CURRENT_KDF_PROFILE;
  if (!input.allowTestProfile) assertProductionProfile(profile);

  const salt = newKdfSalt();
  const kek = await deriveKeyEncryptionKey(input.passphrase, salt, profile, {
    ...(input.onProgress ? { onProgress: input.onProgress } : {}),
  });
  const { key, wrapped, sentinel } = await createVaultMasterKey(
    kek,
    input.vaultId,
    input.keyRecordId,
  );

  return {
    vaultMasterKey: key,
    keyRecord: {
      id: input.keyRecordId,
      kind: 'primary',
      kdf_profile_id: profile.id,
      kdf_salt: bytesToBase64(salt),
      wrapped_vmk: wrappedKeyToRecord(wrapped),
      sentinel: blobToRecord(sentinel),
    },
  };
}

export interface UnlockVaultInput {
  readonly passphrase: string;
  readonly vaultId: string;
  /** Every key record for the vault. Tried in order. */
  readonly keyRecords: readonly VaultKeyRecord[];
  readonly onProgress?: (fraction: number) => void;
  /** See `CreateVaultInput.allowTestProfile`. Tests only. */
  readonly allowTestProfile?: boolean;
}

export interface UnlockVaultResult {
  readonly vaultMasterKey: CryptoKey;
  readonly keyRecordId: string;
  /**
   * Which record opened. `duress` means the caller must render the decoy view and
   * fire the silent alert — see spec §6.3. The crypto layer only reports it.
   */
  readonly kind: VaultKeyKind;
}

/**
 * Try the passphrase against each key record.
 *
 * Cost note: this runs Argon2id once per record, so a vault with a duress record
 * takes up to twice as long to report a *wrong* passphrase. That is not a side
 * channel worth worrying about — a correct primary passphrase returns after one
 * derivation and the attacker learning "this vault has two records" tells them
 * nothing they could not read off the record count anyway.
 */
export async function unlockVault(input: UnlockVaultInput): Promise<UnlockVaultResult> {
  if (input.keyRecords.length === 0) {
    throw new Error('This vault has no key records; it cannot be unlocked.');
  }

  for (const record of input.keyRecords) {
    const profile = resolveKdfProfile(record.kdf_profile_id, input.allowTestProfile ?? false);
    const salt = base64ToBytes(record.kdf_salt);
    const kek = await deriveKeyEncryptionKey(input.passphrase, salt, profile, {
      ...(input.onProgress ? { onProgress: input.onProgress } : {}),
    });

    const sentinelOk = await verifySentinel(
      kek,
      recordToBlob(record.sentinel),
      input.vaultId,
      record.id,
    );
    if (!sentinelOk) continue;

    try {
      const vmk = await unwrapVaultMasterKey(
        kek,
        recordToWrappedKey(record.wrapped_vmk),
        input.vaultId,
        record.id,
      );
      return { vaultMasterKey: vmk, keyRecordId: record.id, kind: record.kind };
    } catch (error) {
      if (error instanceof AeadError) {
        // The sentinel opened but the wrapped key did not. That is not a wrong
        // passphrase — it is a damaged or tampered-with record, and the user needs
        // to know the difference because the remedies are completely different.
        throw new VaultIntegrityError(record.id);
      }
      throw error;
    }
  }

  throw new WrongPassphraseError();
}

/**
 * The sentinel verified but the wrapped master key did not open. The passphrase is
 * right and the stored blob is wrong: database corruption, a bad restore, or
 * tampering. Surfaced distinctly because telling a user "wrong passphrase" here
 * would send them hunting for a transcription error that does not exist.
 */
export class VaultIntegrityError extends Error {
  readonly keyRecordId: string;
  constructor(keyRecordId: string) {
    super(
      'The passphrase is correct but this vault key record failed its integrity check. ' +
        'Do not re-create the vault. Contact support with the key record id; a backup restore is needed.',
    );
    this.name = 'VaultIntegrityError';
    this.keyRecordId = keyRecordId;
  }
}

export interface EnrolDuressInput {
  readonly duressPassphrase: string;
  readonly vaultId: string;
  readonly keyRecordId: string;
  /** Raw bytes of the decoy master key this record should unwrap to. */
  readonly decoyMasterKeyRaw: Uint8Array;
  readonly profile?: KdfProfile;
  /** See `CreateVaultInput.allowTestProfile`. Tests only. */
  readonly allowTestProfile?: boolean;
}

/**
 * Build a duress key record (spec §6.3).
 *
 * The duress passphrase wraps a *different* master key, which encrypts a decoy
 * inventory. There is no path from the duress key to the real one. V1 ships the
 * crypto and the schema for this so that enabling it later needs no migration and
 * no change to the reviewed cryptographic core; the alerting workflow belongs to
 * build-order step 7 and is not implemented.
 */
export async function buildDuressKeyRecord(
  input: EnrolDuressInput,
): Promise<VaultKeyRecord> {
  const profile = input.profile ?? CURRENT_KDF_PROFILE;
  if (!input.allowTestProfile) assertProductionProfile(profile);

  const salt = newKdfSalt();
  const kek = await deriveKeyEncryptionKey(input.duressPassphrase, salt, profile);
  const { wrapped, sentinel } = await wrapVaultMasterKeyBytes(
    kek,
    input.decoyMasterKeyRaw,
    input.vaultId,
    input.keyRecordId,
  );

  return {
    id: input.keyRecordId,
    kind: 'duress',
    kdf_profile_id: profile.id,
    kdf_salt: bytesToBase64(salt),
    wrapped_vmk: wrappedKeyToRecord(wrapped),
    sentinel: blobToRecord(sentinel),
  };
}
